// CC-CEDICT as `simplified<TAB>pinyin<TAB>definitions`, one line per headword, for word lookup.
// Entries sharing a simplified form are merged. Reuses the copy build-wordlist.mjs caches.
import { readFileSync, writeFileSync } from 'node:fs';

const CACHE = 'scripts/compare-segmenters/data/cedict_1_0_ts_utf-8_mdbg.txt';
const OUTPUT = 'static/dictionary-zh.txt';
const ENTRY = /^(\S+) (\S+) \[([^\]]*)\] \/(.*)\/\s*$/;

const MARKS = { a: 'āáǎà', e: 'ēéěè', i: 'īíǐì', o: 'ōóǒò', u: 'ūúǔù', ü: 'ǖǘǚǜ' };

// ma3 -> mǎ: the mark goes on a or e, on the o of ou, otherwise on the last vowel.
function syllable(raw) {
	const match = /^([a-zü:]+)([1-5])$/i.exec(raw);
	if (!match) return raw;
	const letters = match[1].replace(/u:|v/gi, 'ü');
	const tone = Number(match[2]);
	if (tone === 5) return letters;
	const lower = letters.toLowerCase();
	let at = lower.search(/[ae]/);
	if (at === -1) at = lower.indexOf('ou');
	if (at === -1)
		for (let i = lower.length - 1; i >= 0; i--)
			if (MARKS[lower[i]]) {
				at = i;
				break;
			}
	if (at === -1) return letters;
	const mark = MARKS[lower[at]][tone - 1];
	return (
		letters.slice(0, at) +
		(letters[at] === lower[at] ? mark : mark.toUpperCase()) +
		letters.slice(at + 1)
	);
}

const merged = new Map();
for (const line of readFileSync(CACHE, 'utf-8').split('\n')) {
	const match = ENTRY.exec(line);
	if (!match) continue;
	const [, , simplified, pinyin, definitions] = match;
	const reading = pinyin.split(' ').map(syllable).join(' ');
	const meaning = definitions.split('/').join('; ');
	const entries = merged.get(simplified) ?? [];
	entries.push(`${reading}\t${meaning}`);
	merged.set(simplified, entries);
}

const lines = [...merged]
	.sort(([a], [b]) => (a < b ? -1 : 1))
	.map(([word, entries]) => entries.map((entry) => `${word}\t${entry}`).join('\n'));
writeFileSync(
	OUTPUT,
	'# CC-CEDICT (CC BY-SA 4.0), generated by scripts/build-dictionary.mjs. word<TAB>pinyin<TAB>meaning\n' +
		lines.join('\n') +
		'\n'
);
console.log(`${merged.size} headwords to ${OUTPUT}`);
