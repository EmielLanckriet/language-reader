// A seeded generator, as fit.ts's bootstrap, so the intervals are the same every run.
function random(seed) {
	return () => {
		seed = (seed + 0x6d2b79f5) | 0;
		let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
		t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
		return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
	};
}
/** Observed minus predicted, with a 95% interval bootstrapped by word (a word's outcomes move together). */
function residual(list) {
	const byWord = new Map();
	for (const r of list) byWord.set(r.word, [...(byWord.get(r.word) ?? []), r.label - r.p_obs]);
	const groups = [...byWord.values()];
	const mean = (gs) => {
		let s = 0,
			n = 0;
		for (const g of gs)
			for (const x of g) {
				s += x;
				n++;
			}
		return s / n;
	};
	const next = random(13);
	const means = [];
	for (let b = 0; b < 1000; b++)
		means.push(mean(groups.map(() => groups[Math.floor(next() * groups.length)])));
	means.sort((a, b) => a - b);
	return { diff: mean(groups), lo: means[25], hi: means[974], words: groups.length };
}

