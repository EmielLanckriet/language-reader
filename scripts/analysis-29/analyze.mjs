const logit = (p) => Math.log(p / (1 - p));
const sig = (x) => 1 / (1 + Math.exp(-x));
/** Logistic regression with FSRS's logit as offset: Newton steps on [intercept, ...features], ridge 1e-3. */
function fitOffset(list, feats) {
	const k = feats.length + 1;
	let b = new Array(k).fill(0);
	for (let it = 0; it < 50; it++) {
		const g = new Array(k).fill(0),
			H = Array.from({ length: k }, () => new Array(k).fill(0));
		for (const r of list) {
			const x = [1, ...feats.map((f) => f(r))];
			const p = sig(logit(r.p_obs) + x.reduce((s, xi, i) => s + xi * b[i], 0));
			for (let i = 0; i < k; i++) {
				g[i] += (r.label - p) * x[i];
				for (let j = 0; j < k; j++) H[i][j] += p * (1 - p) * x[i] * x[j];
			}
		}
		for (let i = 0; i < k; i++) {
			g[i] -= 1e-3 * b[i];
			H[i][i] += 1e-3;
		}
		const step = solve(H, g);
		b = b.map((bi, i) => bi + step[i]);
		if (Math.max(...step.map(Math.abs)) < 1e-8) break;
	}
	return (r) =>
		sig(logit(r.p_obs) + [1, ...feats.map((f) => f(r))].reduce((s, xi, i) => s + xi * b[i], 0));
}
function solve(A, y) {
	const n = y.length,
		M = A.map((row, i) => [...row, y[i]]);
	for (let c = 0; c < n; c++) {
		let p = c;
		for (let r = c + 1; r < n; r++) if (Math.abs(M[r][c]) > Math.abs(M[p][c])) p = r;
		[M[c], M[p]] = [M[p], M[c]];
		for (let r = 0; r < n; r++)
			if (r !== c) {
				const f = M[r][c] / M[c][c];
				for (let j = c; j <= n; j++) M[r][j] -= f * M[c][j];
			}
	}
	return M.map((row, i) => row[n] / row[i]);
}
