// Generate the Chinese word list the reader segments with.
//
// Segmentation needs only the *headwords* from CC-CEDICT, not its definitions, and that is the
// whole reason this is affordable: measured, 119,899 simplified headwords are 1.00 MB on disk and
// 0.43 MB over the wire, against 3.97 MB for the dictionary complete with glosses. Definitions are
// a slice-3 cost, paid when slice 3 needs them.
//
// The output is a generated artifact under Principle VII's source-versus-artifact rule: its source
// is this script, generation is reproducible by `node scripts/build-wordlist.mjs`, it sits behind a
// hand-written loader, and it is never hand-edited. Committed rather than fetched during the build,
// so a deploy does not depend on a third-party host being up.
//
//   node scripts/build-wordlist.mjs
//
// Writes static/wordlist-zh.txt and src/lib/analyzer/wordlist-version.ts.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
import { join } from 'node:path';

const SOURCE = 'https://www.mdbg.net/chinese/export/cedict/cedict_1_0_ts_utf-8_mdbg.txt.gz';
const CACHE_DIR = 'scripts/compare-segmenters/data';
const CACHE = join(CACHE_DIR, 'cedict_1_0_ts_utf-8_mdbg.txt');
const OUTPUT = 'static/wordlist-zh.txt';
const VERSION_MODULE = 'src/lib/analyzer/wordlist-version.ts';

// Han script only, and nothing absurdly long. A headword containing Latin letters, digits or
// punctuation cannot be matched by a segmenter that only ever looks at runs of hanzi, so carrying
// it would cost bytes for entries that can never be found.
const HEADWORD = /^\p{Script=Han}+$/u;
const LONGEST_SENSIBLE = 8;

async function cedict() {
	if (existsSync(CACHE)) return readFileSync(CACHE, 'utf-8');

	process.stdout.write(`fetching ${SOURCE}\n`);
	const response = await fetch(SOURCE, { signal: AbortSignal.timeout(60_000) });
	if (!response.ok) throw new Error(`${SOURCE} responded ${response.status}`);
	const text = gunzipSync(Buffer.from(await response.arrayBuffer())).toString('utf-8');
	mkdirSync(CACHE_DIR, { recursive: true });
	writeFileSync(CACHE, text);
	return text;
}

const text = await cedict();
const words = new Set();

for (const line of text.split('\n')) {
	if (line.startsWith('#') || line.trim() === '') continue;
	// CC-CEDICT lines read: traditional simplified [pinyin] /gloss/gloss/
	const parts = line.split(' ');
	if (parts.length < 2) continue;
	const simplified = parts[1];
	if (simplified.length <= LONGEST_SENSIBLE && HEADWORD.test(simplified)) words.add(simplified);
}

const sorted = [...words].sort();

// The licence travels with the data, because CC-CEDICT is CC BY-SA 4.0 and this file is a
// derivative of it. The loader skips lines beginning with '#'.
const header = [
	'# Chinese word list for segmentation.',
	'#',
	'# Generated by scripts/build-wordlist.mjs -- do not edit by hand.',
	'# Source: CC-CEDICT (https://www.mdbg.net/chinese/dictionary?page=cedict)',
	'# Licence: Creative Commons Attribution-ShareAlike 4.0 (CC BY-SA 4.0)',
	'#',
	'# Headwords only: the simplified form of each entry. Definitions are deliberately not here --',
	'# segmentation does not need them, and they are four times the size.',
	'#'
].join('\n');

const body = sorted.join('\n');
writeFileSync(OUTPUT, `${header}\n${body}\n`);

// A content hash, so the analyzer's version changes when the data does. Without it a regenerated
// list could carry the old stamp, and documents segmented by two different word lists would sit
// mixed with no way to tell them apart -- the failure ADR-0011 exists to prevent, arriving through
// the data instead of through the code.
const digest = createHash('sha256').update(body).digest('hex').slice(0, 8);
writeFileSync(
	VERSION_MODULE,
	`// Generated by scripts/build-wordlist.mjs -- do not edit by hand.\n` +
		`//\n` +
		`// A content hash of static/wordlist-zh.txt. It is part of the analyzer's version so that\n` +
		`// regenerating the word list restamps every document and re-derives it, rather than leaving\n` +
		`// two different segmentations sharing one version (ADR-0011).\n` +
		`export const WORDLIST_VERSION = '${digest}';\n` +
		`export const WORDLIST_WORDS = ${sorted.length};\n`
);

const multi = sorted.filter((w) => [...w].length > 1).length;
console.log(
	`wordlist: ${sorted.length.toLocaleString()} words (${multi.toLocaleString()} multi-character), ` +
		`hash ${digest}\n  ${OUTPUT}\n  ${VERSION_MODULE}`
);
