// Fetch the vocabulary of the contextual segmentation model, and commit it.
//
// The model itself is 98 MB and is fetched on demand at run time (ADR-0015). Its vocabulary is
// 107 KB, so it is committed instead: it makes the tokenizer a pure function over a local file, it
// keeps startup free of a second network round trip, and it means the vocabulary cannot silently
// disagree with the tokenizer that reads it.
//
// A generated artifact under Principle VII: source is this script, generation is one committed
// command, it sits behind a hand-written tokenizer, and it is never hand-edited.
//
//   node scripts/build-bert-vocab.mjs

import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

const MODEL = 'Xenova/bert-base-chinese-ws';
const SOURCE = `https://huggingface.co/${MODEL}/resolve/main/vocab.txt`;
const OUTPUT = 'static/bert-vocab-zh.txt';
const VERSION_MODULE = 'src/lib/analyzer/bert-vocab-version.ts';

// bert-base-chinese. Asserted rather than assumed: a vocabulary of a different size is a different
// model, and pairing one model's ids with another's vocabulary produces plausible nonsense.
const EXPECTED_ENTRIES = 21128;

const response = await fetch(SOURCE, { signal: AbortSignal.timeout(60_000) });
if (!response.ok) throw new Error(`${SOURCE} responded ${response.status}`);
const text = await response.text();

const lines = text.split('\n').filter((line, index, all) => line !== '' || index < all.length - 1);
if (lines.length !== EXPECTED_ENTRIES) {
	throw new Error(`expected ${EXPECTED_ENTRIES} vocabulary entries, found ${lines.length}`);
}
for (const [token, id] of [
	['[UNK]', 100],
	['[CLS]', 101],
	['[SEP]', 102]
]) {
	if (lines[id] !== token) throw new Error(`expected ${token} at id ${id}, found "${lines[id]}"`);
}

writeFileSync(OUTPUT, `${lines.join('\n')}\n`);

const digest = createHash('sha256').update(lines.join('\n')).digest('hex').slice(0, 8);
writeFileSync(
	VERSION_MODULE,
	`// Generated by scripts/build-bert-vocab.mjs -- do not edit by hand.\n` +
		`//\n` +
		`// A content hash of static/bert-vocab-zh.txt, and the model it belongs to. Both are part of\n` +
		`// the tagger's version, so changing either restamps every document and re-derives it.\n` +
		`export const BERT_VOCAB_VERSION = '${digest}';\n` +
		`export const BERT_MODEL = '${MODEL}';\n` +
		`export const BERT_VOCAB_ENTRIES = ${lines.length};\n`
);

console.log(
	`bert vocab: ${lines.length} entries, hash ${digest}\n  ${OUTPUT}\n  ${VERSION_MODULE}`
);
